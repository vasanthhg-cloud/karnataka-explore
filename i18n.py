def current_lang():
    return session.get("lang", DEFAULT_LANG)


def t(key, **kwargs):
    """Translate a key in the active language."""
    lang = current_lang()
    table = TRANSLATIONS.get(lang) or {}
    value = table.get(key) or TRANSLATIONS[DEFAULT_LANG].get(key) or key
    return value.format(**kwargs) if kwargs else value


